"""Mode library + switching on top of HeSuVi / Equalizer APO.

Library (portable, next to this package):
  modes/<id>/mode.json   {"name", "dolby": {"profile", "ieq"}, "notes", and either "include" or nothing}
  modes/<id>/mode.txt    EAPO filter lines for the mode body (Preamp / GraphicEQ / VSTPlugin ...);
                         "%VST%" is replaced by this PC's EqualizerAPO\\config\\VST folder.
  A mode with "include" (e.g. music-warm.txt) is a link to a file that lives in the HeSuVi folder and is
  maintained elsewhere, so tuning it there flows straight into the app.

Switching writes one generated file, HeSuVi\\soundmode.txt, which postlude.txt includes (one-time migration
from "Include: music-warm.txt"). Every write keeps the previous file in backups\\<timestamp>\\.
"""
import datetime, json, os, re, shutil
from pathlib import Path
from . import detect

ROOT = Path(__file__).resolve().parent.parent
MODES = ROOT / "modes"
BACKUPS = ROOT / "backups"
STATE = ROOT / "state.json"
HSV = detect.HESUVI
VST_DIR = detect.EAPO_CFG / "VST"
ACTIVE = HSV / "soundmode.txt"
POSTLUDE = HSV / "postlude.txt"
GOLDEN_POSTLUDE = ROOT / "hesuvi-control" / "golden" / "postlude.txt"
OUR_INCLUDE = "Include: soundmode.txt"


class Mode:
    def __init__(self, d: Path):
        self.id = d.name; self.dir = d
        self.meta = json.loads((d / "mode.json").read_text(encoding="utf-8"))
        self.name = self.meta.get("name", self.id)

    @property
    def include(self): return self.meta.get("include")

    def body(self):
        if self.include: return f"Include: {self.include}"
        t = (self.dir / "mode.txt").read_text(encoding="utf-8")
        return t.replace("%VST%", str(VST_DIR))


def modes():
    return sorted((Mode(d) for d in MODES.iterdir() if (d / "mode.json").exists()), key=lambda m: m.name) if MODES.exists() else []


def get(mode_id):
    for m in modes():
        if m.id == mode_id: return m
    raise KeyError(f"khong co che do '{mode_id}'")


# ---------------------------------------------------------------- state (per PC, so one portable folder serves many PCs)
def _state():
    try: return json.loads(STATE.read_text(encoding="utf-8"))
    except (OSError, ValueError): return {}


def state():
    return _state().get(os.environ.get("COMPUTERNAME", "pc"), {})


def _save_state(**kw):
    s = _state(); s.setdefault(os.environ.get("COMPUTERNAME", "pc"), {}).update(kw)
    STATE.write_text(json.dumps(s, ensure_ascii=False, indent=1), encoding="utf-8")


# ---------------------------------------------------------------- rendering
def device_guid():
    return detect.eapo_state()["hesuvi_device"]


GUARD_RE = re.compile(r'(regexSearch\(")([0-9a-fA-F-]{36})(")')


# HeSuVi defines its on/off variable ("active", from deact.txt) only inside its own block, which is guarded by the
# headphones in devna.txt. On any other headphones "active" would be undefined and the mode silently off, so the
# generated file defines it itself.
ACTIVE_DEF = "Include: deact.txt\n"


def render(mode: Mode, guid: str):
    head = "Do not edit; switch modes in the app.\n"
    return _render(mode, guid).replace(head, head + ACTIVE_DEF, 1)


def _render(mode: Mode, guid: str):
    body ="\n".join("    " + l if l.strip() else l for l in mode.body().splitlines())
    if mode.include:   # the linked file carries its own device guard
        linked = (HSV / mode.include).read_text(encoding="utf-8-sig") if (HSV / mode.include).exists() else ""
        g = GUARD_RE.search(linked)
        if g and g.group(2).lower() != guid.lower():   # linked file is bound to other headphones: inline a retargeted copy
            return (f"# generated by soundmode - mode: {mode.id} ({mode.name}). Do not edit; switch modes in the app.\n"
                    f"# copy of {mode.include}, retargeted to the current headphones\n" + GUARD_RE.sub(rf"\g<1>{guid}\g<3>", linked) + "\n")
        return f"# generated by soundmode - mode: {mode.id} ({mode.name}). Do not edit; switch modes in the app.\n{mode.body()}\n"
    return (f"# generated by soundmode - mode: {mode.id} ({mode.name}). Do not edit; switch modes in the app.\n"
            f'If: sizeof(regexSearch("{guid}", tolower(deviceGuid))) > 0\n'
            f"  If: active\n    Channel: L R\n{body}\n  EndIf:\nEndIf:\n")


def migrated():
    try: return OUR_INCLUDE in POSTLUDE.read_text(encoding="utf-8-sig")
    except OSError: return False


def plan(mode: Mode, guid=None):
    """Files that apply(mode) would write: {path: new_text}. Pure, nothing written."""
    guid = (guid or device_guid() or "").lower()
    if not guid: raise RuntimeError("Khong doc duoc GUID tai nghe trong HeSuVi\\devna.txt (mo app va bam Set up)")
    out = {ACTIVE: render(mode, guid)}
    if not migrated():
        pl = POSTLUDE.read_text(encoding="utf-8-sig") if POSTLUDE.exists() else ""
        new = re.sub(r"(?mi)^\s*Include:\s*music-warm\.txt\s*$", OUR_INCLUDE, pl) if "music-warm" in pl.lower() else pl.rstrip() + "\n" + OUR_INCLUDE
        out[POSTLUDE] = new.rstrip() + "\n"
        out[GOLDEN_POSTLUDE] = out[POSTLUDE]   # or the logon repair would put the old include back
    return out


def _backup(paths):
    dst = BACKUPS / datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    for p in paths:
        if p.exists():
            dst.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, dst / (p.parent.name + "__" + p.name))
    return dst


def apply(mode: Mode, guid=None):
    files = plan(mode, guid)
    bk = _backup(files)
    for p, t in files.items():
        p.write_text(t, encoding="utf-8")
    dev = device_guid()
    per = dict(state().get("device_modes", {}))   # each pair of headphones (each user) keeps its own last mode
    if dev: per[dev] = mode.id
    _save_state(mode=mode.id, device=dev, device_modes=per, applied=datetime.datetime.now().isoformat(timespec="seconds"))
    return files, bk


def retarget(guid):
    """Point the current mode at other headphones (re-render soundmode.txt for that device GUID)."""
    cur = current() if ACTIVE.exists() or POSTLUDE.exists() else None
    ids = {m.id for m in modes()}
    remembered = state().get("device_modes", {}).get((guid or "").lower())
    for cand in (remembered, cur, state().get("mode"), "music-warm-dolby3", "flat"):   # fresh PC: start from the last-used / default mode
        if cand in ids: return apply(get(cand), guid)
    raise RuntimeError("No mode found in the modes folder")


def current():
    """Mode id actually live in soundmode.txt (None before migration)."""
    if not migrated(): return "music-warm" if "music-warm" in POSTLUDE.read_text(encoding="utf-8-sig").lower() else None
    m = re.search(r"mode: (\S+)", ACTIVE.read_text(encoding="utf-8")) if ACTIVE.exists() else None
    return m.group(1) if m else None


# ---------------------------------------------------------------- on/off (same switch as hesuvi.ps1 on/off)
DEACT = HSV / "deact.txt"


def is_active():
    return detect.eapo_state()["hesuvi_active"]


def set_active(on: bool):
    DEACT.write_text("Eval: active=" + ("true" if on else "false"), encoding="utf-8")
